// Builds src/circuit-paths.ts: the real circuit outlines for the live map, from the
// bacinger/f1-circuits GeoJSON dataset (MIT). Run: node scripts/build-circuit-paths.mjs [f1-circuits.geojson]
// Without a file argument it downloads the dataset.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson';
// Game circuit id -> dataset id. Lengths were checked against the game's figures (all within 0.04 km).
const IDS = {
  melbourne: 'au-1953', shanghai: 'cn-2004', suzuka: 'jp-1962', miami: 'us-2022', montreal: 'ca-1978', monaco: 'mc-1929',
  barcelona: 'es-1991', spielberg: 'at-1969', silverstone: 'gb-1948', spa: 'be-1925', hungaroring: 'hu-1986', zandvoort: 'nl-1948',
  monza: 'it-1922', madrid: 'es-2026', baku: 'az-2016', sepang: 'my-1999', singapore: 'sg-2008', austin: 'us-2012',
  mexico: 'mx-1962', interlagos: 'br-1940', lasvegas: 'us-2023', lusail: 'qa-2004', yasmarina: 'ae-2009',
};
// The dataset traces each lap from the start/finish line in the racing direction, except where noted here.
// Marina Bay is raced anticlockwise; its outline is traced clockwise.
const REVERSE = new Set(['singapore']);
// The live map's drawing box (the track SVG's viewBox is 40 5 440 275; car markers stay inside 51-468 x 16-267).
const BOX = { x: 62, y: 24, w: 396, h: 236 };

const data = JSON.parse(process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(SOURCE)).text());
const byId = new Map(data.features.map(f => [f.properties.id, f]));

/** Ramer-Douglas-Peucker on a closed loop's points (kept in order). */
function simplify(points, epsilon) {
  const keep = new Uint8Array(points.length); keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let worst = -1, index = -1;
    const [ax, ay] = points[a], [bx, by] = points[b], len = Math.hypot(bx - ax, by - ay);
    for (let i = a + 1; i < b; i++) {
      // A closed loop's ends coincide: measure from that point rather than from a zero-length segment.
      const d = len < 1e-9 ? Math.hypot(points[i][0] - ax, points[i][1] - ay)
        : Math.abs((bx - ax) * (ay - points[i][1]) - (ax - points[i][0]) * (by - ay)) / len;
      if (d > worst) { worst = d; index = i; }
    }
    if (worst > epsilon) { keep[index] = 1; stack.push([a, index], [index, b]); }
  }
  return points.filter((_, i) => keep[i]);
}

const out = {};
for (const [game, id] of Object.entries(IDS)) {
  const feature = byId.get(id);
  if (!feature) throw new Error(`Dataset has no circuit ${id} for ${game}`);
  let coords = feature.geometry.coordinates.map(c => [c[0], c[1]]);
  if (Math.hypot(coords[0][0] - coords.at(-1)[0], coords[0][1] - coords.at(-1)[1]) < 1e-9) coords.pop();
  if (REVERSE.has(game)) coords = [coords[0], ...coords.slice(1).reverse()];
  // Local flat projection in metres; y grows southwards, as in SVG.
  const lat0 = coords.reduce((s, c) => s + c[1], 0) / coords.length, k = Math.cos(lat0 * Math.PI / 180) * 111320;
  const flat = coords.map(([lon, lat]) => [lon * k, -lat * 110540]);
  // Rotate to whichever angle lets the shape fill the map box most (shape kept, never mirrored).
  let best = null;
  for (let deg = 0; deg < 180; deg++) {
    const t = deg * Math.PI / 180, cos = Math.cos(t), sin = Math.sin(t);
    const rotated = flat.map(([x, y]) => [x * cos - y * sin, x * sin + y * cos]);
    const xs = rotated.map(p => p[0]), ys = rotated.map(p => p[1]);
    const w = Math.max(...xs) - Math.min(...xs), h = Math.max(...ys) - Math.min(...ys), scale = Math.min(BOX.w / w, BOX.h / h);
    if (!best || scale > best.scale * 1.0001) best = { scale, rotated, minX: Math.min(...xs), minY: Math.min(...ys), w, h };
  }
  const { scale, rotated, minX, minY, w, h } = best;
  const ox = BOX.x + (BOX.w - w * scale) / 2, oy = BOX.y + (BOX.h - h * scale) / 2;
  const placed = rotated.map(([x, y]) => [ox + (x - minX) * scale, oy + (y - minY) * scale]);
  const points = simplify([...placed, placed[0]], 0.45).slice(0, -1);
  out[game] = 'M ' + points.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join(' L ') + ' Z';
  console.log(`${game.padEnd(12)} ${id}  ${feature.geometry.coordinates.length} -> ${points.length} points`);
}

const notice = readFileSync(new URL('./licenses/f1-circuits-LICENSE.md', import.meta.url), 'utf8').trim().split('\n').map(l => `// ${l}`.trimEnd()).join('\n');
writeFileSync(new URL('../src/circuit-paths.ts', import.meta.url), `// Generated by scripts/build-circuit-paths.mjs: do not edit by hand.
// Real circuit outlines for the live map, from https://github.com/bacinger/f1-circuits (MIT; not official
// Formula 1 data). Each path starts at the start/finish line and runs in the racing direction; tracks are
// rotated to fill the map, never mirrored.
//
${notice}

export const CIRCUIT_PATHS: Record<string, string> = ${JSON.stringify(out, null, 2)};
`);
console.log('wrote src/circuit-paths.ts');
